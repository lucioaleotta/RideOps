CREATE TABLE prefissi_telefonici (
    id BIGSERIAL PRIMARY KEY,
    codice_iso2 VARCHAR(2) NOT NULL,
    nome_paese VARCHAR(100) NOT NULL,
    prefisso VARCHAR(10) NOT NULL,
    principale BOOLEAN NOT NULL DEFAULT TRUE,
    attivo BOOLEAN NOT NULL DEFAULT TRUE,
    ordine INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_prefissi_telefonici_iso2 UNIQUE (codice_iso2),
    CONSTRAINT ck_prefissi_telefonici_iso2 CHECK (codice_iso2 ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_prefissi_telefonici_prefisso CHECK (prefisso ~ '^\+[0-9]{1,6}$')
);

CREATE INDEX idx_prefissi_telefonici_attivo_ordine ON prefissi_telefonici (attivo, ordine);

