-- Paesi che condividono il prefisso con un altro: non sono scelti nel parsing di numeri esistenti.
UPDATE prefissi_telefonici
SET principale = FALSE
WHERE codice_iso2 IN ('CA', 'KZ', 'CX', 'CC', 'GG', 'JE', 'IM', 'AX', 'BL', 'MF', 'BQ', 'YT', 'AQ', 'EH', 'SJ');

-- Italia in testa, poi ordine alfabetico per nome.
UPDATE prefissi_telefonici p
SET ordine = ranked.posizione
FROM (
    SELECT id,
           ROW_NUMBER() OVER (ORDER BY (codice_iso2 <> 'IT'), nome_paese) AS posizione
    FROM prefissi_telefonici
) ranked
WHERE p.id = ranked.id;
